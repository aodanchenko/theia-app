#!/usr/bin/env python3
"""Exports the frozen walking models from the Theia MediaPipe standalone package for the browser. Stdlib only (no torch/numpy).

usage: python3 scripts/export-gait.py <Theia_MediaPipe_Standalone dir>
writes: src/engine/gait-tcn.bin (float32 little-endian weights; imported with ?url, so its name is content-hashed and the offline cache never serves stale weights), src/engine/gaitModels.json (layout, labels, density models),
        src/engine/gait.fixture.json (the package's own TCN replay fixture, for the TS port's test)
"""
import json, pickle, struct, sys, zipfile
from pathlib import Path

src = Path(sys.argv[1]) / 'models'
out = Path(__file__).resolve().parent.parent

# TCN checkpoint: a torch zip; rebuild tensors as (storage key, shape) without torch. All tensors are contiguous float32.
z = zipfile.ZipFile(src / 'tcn_state.pt')
root = z.namelist()[0].split('/')[0]
class Unpickler(pickle.Unpickler):
    def find_class(self, mod, name):
        if (mod, name) == ('torch._utils', '_rebuild_tensor_v2'): return lambda storage, offset, shape, stride, *_: (storage[2], offset, list(shape))
        if (mod, name) == ('collections', 'OrderedDict'): return dict
        if mod == 'torch': return name
        raise pickle.UnpicklingError(f'unexpected {mod}.{name}')
    def persistent_load(self, pid): return pid
state = Unpickler(z.open(f'{root}/data.pkl')).load()
blob, layout = bytearray(), []
for name, (key, offset, shape) in state.items():
    if name.startswith('numeric_heads.1'): continue  # second numeric head = other pose method, unused
    n = 1
    for s in shape: n *= s
    data = z.read(f'{root}/data/{key}')[offset * 4:(offset + n) * 4]
    assert len(data) == n * 4, name
    layout.append([name, shape, len(blob) // 4])
    blob += data
(out / 'src/engine/gait-tcn.bin').write_bytes(blob)

protocol = json.loads((src / 'tcn_label_protocol.json').read_text())
density = json.loads((src / 'density_models.json').read_text())
keep = ['center', 'scale', 'means', 'covariances', 'mixture_weights', 'feature_bands']
models = {
    'note': 'GENERATED by scripts/export-gait.py from the Theia MediaPipe standalone package. Developed on Sapiens2 poses; not validated on MediaPipe.',
    'tcn': {
        'tensors': layout,
        'normalization': json.loads((src / 'tcn_normalization.json').read_text())['sapiens'],
        'labels': [{k: l[k] for k in ['id', 'outcome', 'direction', 'region', 'classification_enabled']} for l in protocol['labels']],
        'outcomes': [{k: o.get(k) for k in ['id', 'view', 'unit', 'label', 'free_arm_only']} for o in protocol['outcomes']],
    },
    # fold 0 only (the package default), both supported views
    'density': {view: {m['region']: {**{k: m[k] for k in keep}, 'calibration': [[s, w] for s, w in zip(m['calibration_scores'], m['calibration_weights'])]}
                       for m in density.values() if m['fold'] == 0 and m['view'] == view and m['status'] == 'trained'} for view in ['side', 'front_rear']},
}
(out / 'src/engine/gaitModels.json').write_text(json.dumps(models, separators=(',', ':')))

# .npy reader for the replay fixture (little-endian float32, C order)
def npy(data):
    hlen = struct.unpack('<H', data[8:10])[0]
    header = eval(data[10:10 + hlen].decode('latin1'))
    assert header['descr'] == '<f4' and not header['fortran_order']
    return {'shape': list(header['shape']), 'data': [round(v, 7) for v in struct.unpack(f'<{len(data[10 + hlen:]) // 4}f', data[10 + hlen:])]}
fz = zipfile.ZipFile(Path(sys.argv[1]) / 'tests/replay_fixture.npz')
(out / 'src/engine/gait.fixture.json').write_text(json.dumps({n[:-4]: npy(fz.read(n)) for n in fz.namelist()}, separators=(',', ':')))
print(f'tcn {len(blob) // 4} floats, density views', {v: len(m) for v, m in models['density'].items()})
