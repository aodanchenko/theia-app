// Vite plugin: builds one service worker per installable app (sw-earth.js, sw-space.js). Each precaches only the
// files its own page needs, so installing Earth never downloads Space code and the other way round.
import type { Plugin } from 'vite'

const APPS = { earth: 'pages/EarthPage.tsx', space: 'pages/SpacePage.tsx' } as const

type Chunk = { type: 'chunk'; fileName: string; isEntry: boolean; facadeModuleId: string | null; imports: string[]; viteMetadata?: { importedCss: Set<string>; importedAssets: Set<string> } }
type Bundle = Record<string, Chunk | { type: 'asset'; fileName: string }>

// Files a page needs on first paint: the entry, the page chunk, everything they import, and their CSS and assets.
export function precacheFor(bundle: Bundle, page: string): string[] {
  const chunks = Object.values(bundle).filter((c): c is Chunk => c.type === 'chunk')
  const files = new Set<string>()
  const walk = (c: Chunk | undefined) => {
    if (!c || files.has(c.fileName)) return
    files.add(c.fileName)
    c.viteMetadata?.importedCss.forEach((f) => files.add(f))
    c.viteMetadata?.importedAssets.forEach((f) => files.add(f))
    c.imports.forEach((f) => walk(bundle[f] as Chunk))
  }
  walk(chunks.find((c) => c.isEntry))
  const pageChunk = chunks.find((c) => c.facadeModuleId?.endsWith(page))
  if (!pageChunk) throw new Error(`pwa: no chunk for ${page}`)
  walk(pageChunk)
  return [...files].map((f) => `/${f}`)
}

// The worker: app shell precached on install; the page itself network-first (fresh when online, cached offline);
// everything else (pose model, fonts, photos) cached the first time it loads, in a cache that survives app updates.
export function workerSource(app: string, precache: string[], version: string): string {
  return `// Generated by scripts/pwa.ts. Theia ${app}: offline cache.
const SHELL = 'theia-${app}-${version}', RUNTIME = 'theia-${app}-runtime', PAGE = '/${app}'
const PRECACHE = ${JSON.stringify([`/${app}`, ...precache, `/${app}.webmanifest`, '/icon-192.png', '/icon-512.png', '/icon-mask.png', '/icon.svg'])}

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('theia-${app}-') && k !== SHELL && k !== RUNTIME).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || req.url.startsWith('chrome-extension:')) return
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((res) => { const copy = res.clone(); if (res.ok) caches.open(SHELL).then((c) => c.put(PAGE, copy)); return res }).catch(() => caches.match(PAGE, { ignoreVary: true })))
    return
  }
  // ignoreVary: the server varies on Origin, and a <link crossorigin> sends one while the precache fetch did not.
  e.respondWith(caches.match(req, { ignoreVary: true }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok || res.type === 'opaque') { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)) }
    return res
  })))
})
`
}

export default function pwa(): Plugin {
  return {
    name: 'theia-pwa',
    apply: 'build',
    generateBundle(_, bundle) {
      const version = Date.now().toString(36)
      for (const [app, page] of Object.entries(APPS)) {
        this.emitFile({ type: 'asset', fileName: `sw-${app}.js`, source: workerSource(app, precacheFor(bundle as unknown as Bundle, page), version) })
      }
    },
  }
}
